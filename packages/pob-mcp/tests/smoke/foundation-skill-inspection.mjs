import { strict as assert } from 'node:assert';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { PoBLuaApiClient } from '../../build/adapters/pob/bridge.js';
import { gearedBuildXml, smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';
const dir = await mkdtemp(join(tmpdir(), 'pob-skill-inspect-'));
const client = new PoBLuaApiClient({ cwd: smokePoBSrc(), cmd: process.env.POB_CMD, args: [resolve('lua/vanilla_stdio_bridge.lua')], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
let child;
try {
  await client.start(); await client.loadBuildXml(await readFile(gearedBuildXml, 'utf8'));
  const main = await client.createSocketGroup({ label: 'minion', slot: 'Helmet' });
  await client.addGem({ groupIndex: main.index, gemName: 'Summon Raging Spirit', level: 20 });
  await client.addGem({ groupIndex: main.index, gemName: 'Minion Damage Support', level: 19, quality: 12 });
  await client.setMainSelection({ mainSocketGroup: main.index });
  const other = await client.createSocketGroup({ label: 'disabled fixture', slot: 'Gloves' });
  await client.addGem({ groupIndex: other.index, gemName: 'Fireball', level: 15 });
  await client.setSocketGroupEnabled({ groupIndex: other.index, enabled: false });
  const native = await client.getSkills();
  const source = native.groups.find(group => group.index === main.index);
  assert.equal(source.gems[0].supportClassificationKnown, true); assert.equal(source.gems[1].supportClassificationKnown, true);
  assert.equal(source.gems[1].isSupport, true); assert.equal(source.gems[1].appliedToSelectedSkill, true);
  const { xml } = await client.unchangedItemsSnapshot();
  await client.setSocketGroupEnabled({ groupIndex: other.index, enabled: true });
  await client.addGem({ groupIndex: other.index, gemName: 'Melee Physical Damage Support', level: 20 });
  await client.setMainSelection({ mainSocketGroup: other.index });
  const incompatible = (await client.getSkills()).groups.find(group => group.index === other.index).gems[1];
  assert.equal(incompatible.supportClassificationKnown, true);
  assert.equal(incompatible.appliedToSelectedSkill, false);
  const { xml: incompatibleXml } = await client.unchangedItemsSnapshot(); await client.stop();
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: resolve('lua/vanilla_stdio_bridge.lua') });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'skill-inspection-smoke', version: '1' } }); mcp.notify('notifications/initialized', {});
  const call = async (name, args) => { const response = await mcp.request('tools/call', { name, arguments: args }); assert.ok(!response.error && !response.result?.isError, JSON.stringify(response).slice(0, 1000)); return JSON.parse(response.result.content[0].text); };
  const parent = await call('foundation_import_build', { xml, source: 'skill-inspection-fixture' });
  const report = await call('inspect_snapshot_skill_groups', { snapshot_id: parent.id });
  assert.equal(report.mainGroupIndex, main.index); assert.equal(report.groups.length, 1);
  assert.equal(report.groups[0].gems[0].kind, 'active'); assert.equal(report.groups[0].gems[1].kind, 'support');
  assert.equal(report.groups[0].gems[1].appliedToSelectedSkill, true);
  assert.equal(report.groups[0].assessment.state, 'active');
  assert.ok(!report.groups[0].assessment.issues.includes('support_not_applied'));
  assert.equal(report.groups[0].gems[1].level, 19); assert.equal(report.groups[0].gems[1].quality, 12);
  const validScan = await call('check_snapshot_issues', { snapshot_id: parent.id });
  assert.ok(!validScan.issues.some(issue => issue.code === 'support_not_applied_to_selected_skill' && issue.evidence.gemName === 'Minion Damage Support'));
  const incompatibleParent = await call('foundation_import_build', { xml: incompatibleXml, source: 'incompatible-support-fixture' });
  const incompatibleScan = await call('check_snapshot_issues', { snapshot_id: incompatibleParent.id });
  assert.equal(incompatibleScan.checks.selectedSkillSupports, 'checked');
  assert.ok(incompatibleScan.issues.some(issue => issue.code === 'support_not_applied_to_selected_skill' && issue.evidence.groupIndex === other.index && issue.evidence.gemIndex === incompatible.index));
  const incompatibleReport = await call('inspect_snapshot_skill_groups', { snapshot_id: incompatibleParent.id });
  assert.ok(incompatibleReport.groups[0].assessment.issues.includes('support_not_applied'));
  assert.ok(incompatibleReport.groups[0].assessment.notAppliedSupportIndices.includes(incompatible.index));
  const all = await call('inspect_snapshot_skill_groups', { snapshot_id: parent.id, all_groups: true });
  assert.equal(all.groups.find(group => group.index === other.index).enabled, false);
  const placeholder = native.groups.flatMap(group => group.gems.filter(gem => !gem.name && gem.supportClassificationKnown === false).map(gem => ({ groupIndex: group.index, gemIndex: gem.index })))[0];
  assert.ok(placeholder); assert.ok(all.unknownGemTypes.some(value => value.groupIndex === placeholder.groupIndex && value.gemIndex === placeholder.gemIndex));
  const explicit = await call('inspect_snapshot_skill_groups', { snapshot_id: parent.id, group_index: other.index });
  assert.equal(explicit.groups[0].gems[0].name, 'Fireball'); assert.equal(explicit.groups[0].enabled, false);
  assert.equal((await call('foundation_export_build', { snapshot_id: parent.id })).xml, xml);
  child.stdin.end(); assert.equal((await exited)[0], 0); console.log('foundation skill inspection passed');
} finally { if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM'); await client.stop(); await rm(dir, { recursive: true, force: true }); }
