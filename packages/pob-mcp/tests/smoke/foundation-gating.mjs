import { strict as assert } from 'node:assert';
import { mkdtemp, rm, access, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { startMcpServer } from './mcpClient.mjs';
import { JobStore } from '../../build/foundation/jobStore.js';
import { SnapshotStore } from '../../build/foundation/snapshotStore.js';
const dir = await mkdtemp(join(tmpdir(), 'pob-gating-'));
const clients = [];
function start(env) { const c = startMcpServer(env); c.child.stderr.on('data', () => {}); clients.push(c.child); return c; }
async function init(c) { await c.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'gating', version: '1' } }); c.notify('notifications/initialized', {}); }
try {
  const disabled = start({ POB_FOUNDATION_ENABLED: 'false' });
  await init(disabled);
  const tools = await disabled.request('tools/list', {});
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_import_build'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_selection'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_gem'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_gem_list'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_skill_group'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_skill_group_enabled'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_remove_skill_group'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_flask_active'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_item_sets'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_item_set'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_specs'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_derive_spec'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_create_spec'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_rename_spec'));
  assert.ok(!tools.result.tools.some(t => t.name === 'foundation_delete_spec'));
  assert.ok(!tools.result.tools.some(t => t.name === 'reference_currency_rates'));
  assert.ok(!tools.result.tools.some(t => t.name === 'screen_currency_spreads'));
  assert.ok(!tools.result.tools.some(t => t.name === 'estimate_snapshot_cost'));
  assert.ok(!tools.result.tools.some(t => t.name === 'compare_snapshot_trees'));
  const hidden = await disabled.request('tools/call', { name: 'foundation_import_build', arguments: { xml: '<x/>', source: 'test' } });
  assert.equal(hidden.result.isError, true);
  disabled.child.stdin.end(); await once(disabled.child, 'exit');
  const jobs = new JobStore(join(dir, 'jobs'));
  const snapshot = await new SnapshotStore(dir).create({ xml: '<build/>', source: 'gating', parentId: null, engineVersion: null, dataVersion: null, adapterVersion: null });
  const abandoned = await jobs.create(1, [{ snapshotId: snapshot.id }]);
  await jobs.start(abandoned.id);
  const first = start({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POE_TRADE_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir });
  await init(first);
  assert.equal((await jobs.get(abandoned.id)).status, 'interrupted');
  const foundationOnly = await first.request('tools/list', {});
  assert.ok(foundationOnly.result.tools.some(t => t.name === 'foundation_import_build'));
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_selection').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_gem').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_gem_list').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_skill_group').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_skill_group_enabled').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_remove_skill_group').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_flask_active').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_item_sets').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_item_set').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_specs').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_derive_spec').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_create_spec').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_rename_spec').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'foundation_delete_spec').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'reference_currency_rates').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'simulate_reference_currency_chain').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'screen_currency_spreads').length, 1);
  const invalidSpecOption = await first.request('tools/call', { name: 'foundation_create_spec', arguments: { snapshot_id: snapshot.id, copyFrom: 1 } });
  assert.equal(invalidSpecOption.result.isError, true);
  assert.match(invalidSpecOption.result.content[0].text, /Invalid passive spec creation option/);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'estimate_snapshot_cost').length, 1);
  assert.equal(foundationOnly.result.tools.filter(t => t.name === 'compare_snapshot_trees').length, 1);
  assert.ok(foundationOnly.result.tools.some(t => t.name === 'compare_craft_budget'));
  assert.ok(foundationOnly.result.tools.some(t => t.name === 'simulate_simple_annul'));
  assert.ok(!foundationOnly.result.tools.some(t => t.name === 'estimate_trade_comparable'));
  const tradeDenied = await first.request('tools/call', { name: 'estimate_trade_comparable', arguments: { league: 'Standard', base_type: 'Gold Ring', stat_groups: [] } });
  assert.equal(tradeDenied.result.isError, true);
  const searchDenied = await first.request('tools/call', { name: 'search_official_trade', arguments: { league: 'Standard' } });
  assert.equal(searchDenied.result.isError, true);
  assert.ok(!foundationOnly.result.tools.some(t => t.name === 'sample_trade_item_price'));
  assert.equal((await first.request('tools/call', { name: 'sample_trade_item_price', arguments: { league: 'Standard', item_name: 'Goldrim' } })).result.isError, true);
  assert.ok(!foundationOnly.result.tools.some(t => t.name === 'list_builds'));
  const budget = await first.request('tools/call', { name: 'compare_craft_budget', arguments: { scenarios: [{ name: 'fixture', success_probability: 0.5, chaos_per_attempt: 2, probability_source: 'test fixture' }] } });
  assert.ok(!budget.error && !budget.result?.isError, JSON.stringify(budget));
  assert.equal(JSON.parse(budget.result.content[0].text).scenarios[0].expectedChaos, 4);
  const annul = await first.request('tools/call', { name: 'simulate_simple_annul', arguments: { rarity: 'rare', affixes: [{ name: 'keep', disposition: 'keep' }, { name: 'remove', disposition: 'remove' }], no_fractured: true, no_protection: true, no_catalyst: true, no_corruption: true, no_mirrored: true, no_special_rules: true } });
  assert.ok(!annul.error && !annul.result?.isError, JSON.stringify(annul));
  assert.equal(JSON.parse(annul.result.content[0].text).desiredRemovalProbability, 0.5);
  const denied = await first.request('tools/call', { name: 'list_builds', arguments: {} });
  assert.equal(denied.result.isError, true);
  const resources = await first.request('resources/list', {});
  assert.deepEqual(resources.result.resources, []);
  const second = start({ POB_FOUNDATION_ENABLED: 'true', POB_SNAPSHOT_DIRECTORY: dir });
  const [secondCode] = await once(second.child, 'exit');
  assert.notEqual(secondCode, 0);
  await access(join(dir, '.writer.lock'));
  first.child.stdin.end();
  const [code] = await once(first.child, 'exit');
  assert.equal(code, 0);
  await assert.rejects(access(join(dir, '.writer.lock')));
  const newTrade = start({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POE_TRADE_ENABLED: 'true', POB_SNAPSHOT_DIRECTORY: dir });
  await init(newTrade);
  const tradeTools = await newTrade.request('tools/list', {});
  assert.equal(tradeTools.result.tools.filter(t => t.name === 'estimate_trade_comparable').length, 1);
  assert.equal(tradeTools.result.tools.filter(t => t.name === 'search_official_trade').length, 1);
  assert.equal(tradeTools.result.tools.filter(t => t.name === 'sample_trade_item_price').length, 1);
  assert.equal(tradeTools.result.tools.filter(t => t.name === 'search_trade_stats').length, 1);
  assert.equal(tradeTools.result.tools.filter(t => t.name === 'list_trade_leagues').length, 1);
  assert.ok(!tradeTools.result.tools.some(t => t.name === 'estimate_comparable_item'));
  newTrade.child.stdin.end(); assert.equal((await once(newTrade.child, 'exit'))[0], 0);
  const compat = start({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'true', POE_TRADE_ENABLED: 'true', POB_SNAPSHOT_DIRECTORY: dir });
  await init(compat);
  const combined = await compat.request('tools/list', {});
  assert.ok(combined.result.tools.some(t => t.name === 'foundation_import_build'));
  assert.ok(combined.result.tools.some(t => t.name === 'list_builds'));
  assert.ok(combined.result.tools.some(t => t.name === 'estimate_comparable_item'));
  assert.ok(!combined.result.tools.some(t => t.name === 'estimate_trade_comparable'));
  assert.ok(!combined.result.tools.some(t => t.name === 'search_trade_stats'));
  assert.ok(!combined.result.tools.some(t => t.name === 'search_official_trade'));
  assert.ok(!combined.result.tools.some(t => t.name === 'sample_trade_item_price'));
  assert.equal(combined.result.tools.filter(t => t.name === 'compare_craft_budget').length, 1);
  assert.equal(combined.result.tools.filter(t => t.name === 'simulate_simple_annul').length, 1);
  assert.equal(combined.result.tools.filter(t => t.name === 'estimate_snapshot_cost').length, 1);
  compat.child.stdin.end();
  const [compatCode] = await once(compat.child, 'exit');
  assert.equal(compatCode, 0);
  const corrupt = await jobs.create(1);
  await writeFile(join(dir, 'jobs', `${corrupt.id}.json`), '{');
  const broken = start({ POB_FOUNDATION_ENABLED: 'true', POB_SNAPSHOT_DIRECTORY: dir });
  const [brokenCode] = await once(broken.child, 'exit');
  assert.notEqual(brokenCode, 0);
  await assert.rejects(access(join(dir, '.writer.lock')));
  console.log('foundation gating and store ownership passed');
} finally {
  for (const child of clients) if (child.exitCode === null && child.signalCode === null) child.kill('SIGTERM');
  await rm(dir, { recursive: true, force: true });
}
