import { strict as assert } from 'node:assert';
import { mkdtemp, rm, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { PoBLuaApiClient } from '../../build/adapters/pob/bridge.js';
import { BuildFoundation } from '../../build/foundation/buildFoundation.js';
import { SnapshotStore } from '../../build/foundation/snapshotStore.js';
import { openPoBEngine } from '../../build/adapters/pob/engine.js';
import { smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';
import { once } from 'node:events';
const dir = await mkdtemp(join(tmpdir(), 'pob-mastery-'));
const options = { cwd: smokePoBSrc(), command: process.env.POB_CMD, adapterPath: resolve('lua/vanilla_stdio_bridge.lua'), timeoutMs: 60000 };
const client = new PoBLuaApiClient({ cwd: options.cwd, cmd: options.command, args: [options.adapterPath], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
try {
  await client.start();
  await client.newBuild({ className: 'Witch' });
  await client.setTree({ classId: 3, ascendClassId: 0, nodes: [], treeVersion: '3_29' });
  const group = await client.createSocketGroup({ label: 'poison-minion', slot: 'Helmet' });
  await client.addGem({ groupIndex: group.index, gemName: 'Summon Raging Spirit', level: 20 });
  await client.setMainSelection({ mainSocketGroup: group.index });
  assert.ok((await client.setConfig({ customMods: 'Minions have 100% chance to Poison on Hit' })).applied.customMods);
  const nodes = await client.searchNodes({ keyword: 'Life Mastery', nodeType: 'mastery', maxResults: 100, includeAllocated: false });
  const mastery = nodes.nodes.find(node => node.id === 4139);
  assert.ok(mastery?.pathNodes?.length);
  const initialTree = await client.getTree();
  const autoLevelXml = await client.exportBuildXml();
  await client.setLevel(90);
  const unallocatedXml = await client.exportBuildXml();
  await client.setTree({ ...initialTree, nodes: [...initialTree.nodes, ...mastery.pathNodes], masteryEffects: { 4139: 47642 } });
  const xml = await client.exportBuildXml();
  await client.stop();
  const foundation = new BuildFoundation(new SnapshotStore(dir), () => openPoBEngine(options));
  const unallocated = await foundation.importBuild(unallocatedXml, 'unallocated-mastery-fixture');
  assert.deepEqual((await foundation.masteryOptions(unallocated.id)).masteries, []);
  const nodeOptions = await foundation.masteryNodeOptions(unallocated.id, 4139);
  assert.equal(nodeOptions.allocated, false);
  assert.equal(nodeOptions.treeVersion, '3_29');
  assert.ok(nodeOptions.availableEffects.some(effect => effect.effectId === 31822));
  await assert.rejects(foundation.masteryNodeOptions(unallocated.id, 99999999), /unavailable/);
  await assert.rejects(foundation.deriveTree(unallocated.id, mastery.pathNodes, [], { 4139: 999999 }), /Invalid new mastery effect/);
  const autoLevel = await foundation.importBuild(autoLevelXml, 'auto-level-fixture');
  const autoDerived = await foundation.deriveTree(autoLevel.id, mastery.pathNodes, [], { 4139: 47642 });
  const autoState = await foundation.inspect(autoDerived.id, ['build', 'tree']);
  assert.equal(autoState.data.tree.masteryEffects['4139'], 47642);
  assert.ok(autoState.data.build.level > 1);
  assert.match(await foundation.exportBuild(autoDerived.id), /characterLevelAutoMode="true"/);
  assert.equal(await foundation.exportBuild(autoLevel.id), autoLevelXml);
  const allocated = await foundation.deriveTree(unallocated.id, mastery.pathNodes, [], { 4139: 47642 });
  const allocatedTree = await foundation.inspect(allocated.id, ['tree']);
  await assert.rejects(foundation.deriveTreePaths(unallocated.id, [4139]), /requires an effect/);
  const byPath = await foundation.deriveTreePaths(unallocated.id, [4139], { 4139: 47642 }, true);
  assert.deepEqual((await foundation.inspect(byPath.snapshot.id, ['tree'])).data.tree, allocatedTree.data.tree);
  assert.ok(mastery.pathNodes.every(node => allocatedTree.data.tree.nodes.includes(node)));
  assert.equal(allocatedTree.data.tree.masteryEffects['4139'], 47642);
  const masteryRemoval = await foundation.trialTreeRemoval(allocated.id, 4139);
  assert.ok(masteryRemoval.removed.some(node => node.id === 4139));
  assert.equal((await foundation.inspect(masteryRemoval.snapshot.id, ['tree'])).data.tree.masteryEffects['4139'], undefined);
  assert.equal((await foundation.inspect(allocated.id, ['tree'])).data.tree.masteryEffects['4139'], 47642);
  assert.equal((await foundation.inspect(unallocated.id, ['tree'])).data.tree.masteryEffects['4139'], undefined);
  const completeTree = allocatedTree.data.tree;
  const target = { classId: completeTree.classId, ascendClassId: completeTree.ascendClassId, secondaryAscendClassId: completeTree.secondaryAscendClassId, treeVersion: completeTree.treeVersion, nodes: completeTree.nodes, masteryEffects: completeTree.masteryEffects };
  const twoSpecs = await foundation.deriveCreateSpec(unallocated.id, { title: 'Preserved', copyFrom: 1, activate: false });
  const replaced = await foundation.deriveTreeReplacement(twoSpecs.id, target);
  assert.deepEqual((await foundation.inspect(replaced.id, ['tree'])).data.tree, completeTree);
  const inactive = await foundation.deriveSpec(replaced.id, 2);
  assert.deepEqual((await foundation.inspect(inactive.id, ['tree'])).data.tree, (await foundation.inspect(unallocated.id, ['tree'])).data.tree);
  await assert.rejects(foundation.deriveTreeReplacement(twoSpecs.id, { ...target, masteryEffects: { 4139: 999999 } }), /mastery|complete requested tree/i);

  const parent = await foundation.importBuild(xml, 'mastery-fixture');
  const tattooNode = mastery.pathNodes.find(id => id !== 4139); assert.ok(tattooNode);
  const tattooXml = xml.replace('</Spec>', `<Overrides><Override nodeId="${tattooNode}" dn="Honoured Tattoo of the Oak"/></Overrides></Spec>`);
  assert.notEqual(tattooXml, xml);
  const tattooParent = await foundation.importBuild(tattooXml, 'allocated-tattoo-fixture');
  const tattooTree = (await foundation.inspect(tattooParent.id, ['tree'])).data.tree;
  assert.ok(tattooTree.nodes.includes(tattooNode));
  const tattooTarget = { classId: tattooTree.classId, ascendClassId: tattooTree.ascendClassId, secondaryAscendClassId: tattooTree.secondaryAscendClassId, treeVersion: tattooTree.treeVersion, nodes: tattooTree.nodes, masteryEffects: tattooTree.masteryEffects };
  const tattooLife = await foundation.evaluate(tattooParent.id, ['Life']);
  assert.notEqual(tattooLife.metrics.Life.value, (await foundation.evaluate(parent.id, ['Life'])).metrics.Life.value);
  const tattooChild = await foundation.deriveTreeReplacement(tattooParent.id, tattooTarget, false, 'preserve');
  assert.equal((await foundation.evaluate(tattooChild.id, ['Life'])).metrics.Life.value, tattooLife.metrics.Life.value);
  assert.match(await foundation.exportBuild(tattooChild.id), /Honoured Tattoo of the Oak/);
  const optionsResult = await foundation.masteryOptions(parent.id);
  assert.equal(optionsResult.treeVersion, '3_29');
  const lifeOptions = optionsResult.masteries.find(node => Number(node.nodeId) === 4139);
  assert.ok(lifeOptions?.availableEffects.some(effect => effect.effectId === 31822 && typeof effect.stat === 'string' && effect.stat.length > 0));
  const before = await foundation.evaluate(parent.id, ['Life']);
  const child = await foundation.deriveMasteries(parent.id, { 4139: 31822 });
  const after = await foundation.evaluate(child.id, ['Life']);
  const minionBefore = await foundation.evaluate(parent.id, ['MinionTotalDPS', 'MinionCombinedDPS']);
  const minionAfter = await foundation.evaluate(child.id, ['MinionTotalDPS', 'MinionCombinedDPS']);
  assert.ok(minionBefore.metrics.MinionCombinedDPS.value > minionBefore.metrics.MinionTotalDPS.value);
  assert.notEqual(before.stats.Life, after.stats.Life);
  const inspected = await foundation.inspect(child.id, ['tree']);
  assert.equal(inspected.data.tree.masteryEffects['4139'], 31822);
  assert.equal((await foundation.inspect(parent.id, ['tree'])).data.tree.masteryEffects['4139'], 47642);
  await assert.rejects(foundation.deriveMasteries(parent.id, { 4139: 999999 }), /Invalid or unallocated mastery effect/);
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_SNAPSHOT_DIRECTORY: dir, POB_DIRECTORY: dir, POB_ADAPTER_PATH: options.adapterPath });
  mcp.child.stderr.on('data', () => {});
  const exited = once(mcp.child, 'exit');
  try {
    await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'mastery-smoke', version: '1' } });
    mcp.notify('notifications/initialized', {});
    const call = async (name, args) => {
      const response = await mcp.request('tools/call', { name, arguments: args });
      assert.ok(!response.error && !response.result?.isError, JSON.stringify(response));
      return JSON.parse(response.result.content[0].text);
    };
    const targetWithNotes = await foundation.deriveNotes(twoSpecs.id, 'TARGET_KEEP');
    const targetXml = await foundation.exportBuild(targetWithNotes.id);
    await writeFile(join(dir, 'target.xml'), targetXml);
    const transplanted = await call('transplant_snapshot_tree', { source_snapshot_id: allocated.id, target_snapshot_id: targetWithNotes.id });
    assert.equal(transplanted.snapshot.parentId, targetWithNotes.id);
    assert.equal((await foundation.inspect(transplanted.snapshot.id, ['tree'])).data.tree.masteryEffects['4139'], 47642);
    assert.deepEqual((await foundation.inspect(transplanted.snapshot.id, ['tree'])).data.tree, allocatedTree.data.tree);
    assert.equal((await foundation.notes(transplanted.snapshot.id)).notes, 'TARGET_KEEP');
    const inactiveTransplant = await foundation.deriveSpec(transplanted.snapshot.id, 2);
    assert.deepEqual((await foundation.inspect(inactiveTransplant.id, ['tree'])).data.tree, (await foundation.inspect(unallocated.id, ['tree'])).data.tree);
    assert.equal(await readFile(join(dir, 'target.xml'), 'utf8'), targetXml);
    const fingerprint = await call('inspect_local_build_file', { build_name: 'target.xml' });
    const restored = await call('restore_snapshot_file', { snapshot_id: transplanted.snapshot.id, build_name: 'target.xml', expected_current_sha256: fingerprint.sha256 });
    assert.equal(await foundation.exportBuild(restored.backupSnapshotId), targetXml);
    const reloaded = await foundation.importBuild(await readFile(join(dir, 'target.xml'), 'utf8'), 'transplant-reload');
    assert.deepEqual((await foundation.inspect(reloaded.id, ['tree'])).data.tree, allocatedTree.data.tree);
    assert.equal((await foundation.notes(reloaded.id)).notes, 'TARGET_KEEP');
    const badSource = await mcp.request('tools/call', { name: 'transplant_snapshot_tree', arguments: { source_snapshot_id: tattooParent.id, target_snapshot_id: targetWithNotes.id } });
    assert.equal(badSource.result.isError, true);
    assert.match(badSource.result.content[0].text, /overrides/);
    const unallocatedOptions = await call('foundation_mastery_node_options', { snapshot_id: unallocated.id, node_id: 4139 });
    assert.equal(unallocatedOptions.allocated, false);
    const emptyDiscovery = await call('discover_snapshot_mastery_effects', { snapshot_id: unallocated.id });
    assert.deepEqual(emptyDiscovery.effects, []); assert.equal(emptyDiscovery.totalMasteries, 0);
    assert.ok(unallocatedOptions.availableEffects.some(effect => effect.effectId === 31822));
    const allocatedThroughMcp = await call('foundation_derive_tree', { snapshot_id: unallocated.id, add_nodes: mastery.pathNodes, mastery_effects: { 4139: 47642 } });
    assert.equal(allocatedThroughMcp.id, allocated.id);

    const queried = await call('foundation_mastery_options', { snapshot_id: parent.id });
    assert.ok(queried.masteries.some(node => Number(node.nodeId) === 4139));
    const allEffects = await call('discover_snapshot_mastery_effects', { snapshot_id: parent.id, limit: 100 });
    assert.equal(allEffects.totalMasteries, 1);
    assert.ok(allEffects.effects.some(effect => effect.nodeId === 4139 && effect.effectId === 47642 && effect.selected));
    const discoveryPage = await call('discover_snapshot_mastery_effects', { snapshot_id: parent.id, limit: 1 });
    assert.deepEqual(discoveryPage.effects, allEffects.effects.slice(0, 1));
    assert.equal(discoveryPage.nextOffset, allEffects.totalEffects > 1 ? 1 : null);
    const ranking = await call('rank_snapshot_mastery_effects', { snapshot_id: parent.id, node_id: 4139, effect_ids: [31822, 999999], metric: 'Life' });
    assert.equal(ranking.currentEffect, 47642);
    assert.deepEqual(ranking.rankedEffectIds, [31822]);
    assert.equal(ranking.results[0].delta, after.metrics.Life.value - before.metrics.Life.value);
    assert.equal(ranking.results[1].status, 'unavailable');
    const candidateMeta = await call('foundation_read_snapshot', { snapshot_id: ranking.results[0].snapshotId });
    assert.equal(candidateMeta.parentId, parent.id);
    assert.equal((await call('foundation_snapshot_retention', { snapshot_id: ranking.results[0].snapshotId })).kind, 'trial');
    assert.equal((await call('foundation_inspect', { snapshot_id: parent.id, sections: ['tree'] })).data.tree.masteryEffects['4139'], 47642);
    const minionRanking = await call('rank_snapshot_mastery_effects', { snapshot_id: parent.id, node_id: 4139, effect_ids: [31822], metric: 'MinionCombinedDPS' });
    assert.deepEqual(minionRanking.rankedEffectIds, [31822]);
    assert.equal(minionRanking.baseline.value, minionBefore.metrics.MinionCombinedDPS.value);
    assert.equal(minionRanking.results[0].value, minionAfter.metrics.MinionCombinedDPS.value);
    const fourEffects = lifeOptions.availableEffects.slice(0, 4).map(effect => effect.effectId);
    assert.equal(fourEffects.length, 4);
    const batch = await call('rank_snapshot_mastery_effects', { snapshot_id: parent.id, node_id: 4139, effect_ids: fourEffects, metric: 'Life' });
    assert.equal(batch.results.length, 4);
    assert.ok(batch.results.every(result => result.status === 'ok'));
    const discovered = await call('rank_snapshot_mastery_effects', { snapshot_id: parent.id, node_id: 4139, limit: 2, metric: 'Life' });
    const sortedIds = lifeOptions.availableEffects.map(effect => effect.effectId).sort((a, b) => a - b);
    assert.equal(discovered.candidateScope, 'discovered_page');
    assert.deepEqual(discovered.results.map(result => result.effectId), sortedIds.slice(0, 2));
    assert.equal(discovered.totalAvailableEffects, sortedIds.length);
    assert.equal(discovered.nextOffset, sortedIds.length > 2 ? 2 : null);
    const derived = await call('foundation_derive_masteries', { snapshot_id: parent.id, effects: { 4139: 31822 } });
    assert.equal(derived.id, child.id);
    mcp.child.stdin.end();
    assert.equal((await exited)[0], 0);
  } finally {
    if (mcp.child.exitCode === null && mcp.child.signalCode === null) { mcp.child.kill('SIGTERM'); await exited; }
  }

  console.log('foundation mastery roundtrip passed');
} finally { await client.stop(); await rm(dir, { recursive: true, force: true }); }
