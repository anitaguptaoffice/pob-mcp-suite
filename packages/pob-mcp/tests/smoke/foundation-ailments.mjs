import { strict as assert } from 'node:assert';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { PoBLuaApiClient } from '../../build/pobLuaBridge.js';
import { smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';

const dir = await mkdtemp(join(tmpdir(), 'pob-ailments-'));
const client = new PoBLuaApiClient({ cwd: smokePoBSrc(), cmd: process.env.POB_CMD, args: [resolve('lua/vanilla_stdio_bridge.lua')], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
let child;
try {
  await client.start(); await client.loadBuildXml(await readFile(resolve('example-build.xml'), 'utf8'));
  const group = await client.createSocketGroup({ label: 'shock', slot: 'Weapon 1' });
  await client.addGem({ groupIndex: group.index, gemName: 'Arc', level: 20, quality: 0 });
  const otherGroup = await client.createSocketGroup({ label: 'other', slot: 'Weapon 2' });
  await client.addGem({ groupIndex: otherGroup.index, gemName: 'Fireball', level: 20, quality: 0 });
  await client.setMainSelection({ mainSocketGroup: group.index });
  const xml = await client.exportBuildXml();
  const direct = (await client.getAilments()).ailments.find(a => a.name === 'Shock');
  assert.ok(direct && direct.calculatedEffect > 0 && direct.appliedEffect === 0 && !direct.creditedInCalc);
  assert.equal((await client.getAilments()).calculationSelectionMatchesMain, true);
  await client.setCalcsSelection(otherGroup.index);
  assert.equal((await client.getAilments()).calculationSelectionMatchesMain, false);
  const mismatchedXml = await client.exportBuildXml();
  await client.stop();
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: resolve('lua/vanilla_stdio_bridge.lua') });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'ailment-smoke', version: '1' } }); mcp.notify('notifications/initialized', {});
  const call = async (name, args) => { const response = await mcp.request('tools/call', { name, arguments: args }); assert.ok(!response.error && !response.result?.isError, JSON.stringify(response).slice(0, 1600)); return JSON.parse(response.result.content[0].text); };
  const parent = await call('foundation_import_build', { xml, source: 'ailment-fixture' });
  const base = await call('inspect_snapshot_ailments', { snapshot_id: parent.id });
  const shock = base.ailments.find(a => a.name === 'Shock');
  assert.equal(shock.appliedEffect, 0); assert.equal(shock.creditedInCalc, false);
  assert.equal(shock.calculatedEffect, direct.calculatedEffect); assert.ok(shock.thresholdTable.length > 0);
  if (shock.landsOnConfiguredEnemy) assert.ok(base.uncredited.includes('Shock'));
  const mismatched = await call('foundation_import_build', { xml: mismatchedXml, source: 'different-calcs-skill' });
  const mismatchReport = await call('inspect_snapshot_ailments', { snapshot_id: mismatched.id });
  assert.equal(mismatchReport.calculationSelectionMatchesMain, false);
  const mismatchShock = mismatchReport.ailments.find(a => a.name === 'Shock');
  assert.equal(mismatchShock.calculatedEffect, undefined); assert.equal(mismatchShock.thresholdTable, undefined);
  const configured = await call('foundation_derive_config', { snapshot_id: parent.id, config: { conditionEnemyShocked: true, conditionShockEffect: 25 } });
  const changed = await call('inspect_snapshot_ailments', { snapshot_id: configured.id });
  const applied = changed.ailments.find(a => a.name === 'Shock');
  assert.equal(applied.appliedEffect, 25); assert.equal(applied.creditedInCalc, true);
  assert.ok(!changed.uncredited.includes('Shock'));
  assert.equal((await call('inspect_snapshot_ailments', { snapshot_id: parent.id })).ailments.find(a => a.name === 'Shock').appliedEffect, 0);
  assert.equal((await call('foundation_export_build', { snapshot_id: parent.id })).xml, xml);
  child.stdin.end(); assert.equal((await exited)[0], 0); console.log('foundation ailments passed');
} finally { if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM'); await client.stop(); await rm(dir, { recursive: true, force: true }); }
