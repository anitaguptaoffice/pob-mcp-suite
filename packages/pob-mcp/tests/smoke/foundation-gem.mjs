import { strict as assert } from 'node:assert';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { PoBLuaApiClient } from '../../build/pobLuaBridge.js';
import { BuildFoundation } from '../../build/foundation/buildFoundation.js';
import { SnapshotStore } from '../../build/foundation/snapshotStore.js';
import { openPoBEngine } from '../../build/foundation/pobEngineAdapter.js';
import { smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';

const dir = await mkdtemp(join(tmpdir(), 'pob-gem-'));
const options = { cwd: smokePoBSrc(), command: process.env.POB_CMD, adapterPath: resolve('lua/vanilla_stdio_bridge.lua'), timeoutMs: 60000 };
const client = new PoBLuaApiClient({ cwd: options.cwd, cmd: options.command, args: [options.adapterPath], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
try {
  await client.start();
  await client.newBuild({ className: 'Witch' });
  await client.createSocketGroup({ label: 'primary', slot: 'Helmet' });
  await client.addGem({ groupIndex: 1, gemName: 'Arc', level: 20 });
  await client.addGem({ groupIndex: 1, gemName: 'Added Lightning Damage Support', level: 20 });
  await client.createSocketGroup({ label: 'other', slot: 'Gloves' });
  await client.addGem({ groupIndex: 2, gemName: 'Fireball', level: 20 });
  const xml = await client.exportBuildXml();
  await client.stop();
  const foundation = new BuildFoundation(new SnapshotStore(dir), () => openPoBEngine(options));
  const parent = await foundation.importBuild(xml, 'gem-fixture');
  const before = await foundation.inspect(parent.id, ['skills']);
  const legacyXml = xml.replace('<Gem ', '<Gem qualityId="Anomalous" ');
  assert.notEqual(legacyXml, xml);
  const legacyParent = await foundation.importBuild(legacyXml, 'legacy-quality-fixture');
  const legacyInspection = await foundation.inspect(legacyParent.id, ['skills']);
  assert.equal(legacyInspection.data.skills.groups[0].gems[0].qualityId, 'Default');
  assert.ok(legacyInspection.warnings.some(warning => warning.includes('non-default gem qualityId')));
  assert.equal(await foundation.exportBuild(legacyParent.id), legacyXml);
  const beforeGuard = (await foundation.listSnapshots()).snapshots.length;
  await assert.rejects(foundation.deriveLevel(legacyParent.id, 70), /non-default gem qualityId/);
  assert.equal((await foundation.listSnapshots()).snapshots.length, beforeGuard);
  assert.equal(await foundation.exportBuild(legacyParent.id), legacyXml);
  const defaultQuality = await foundation.deriveGem(parent.id, 1, 1, { qualityId: 'Default', quality: 12 });
  const defaultGem = (await foundation.inspect(defaultQuality.id, ['skills'])).data.skills.groups[0].gems[0];
  assert.equal(defaultGem.qualityId, 'Default');
  assert.equal(defaultGem.quality, 12);
  assert.equal((await foundation.inspect(parent.id, ['skills'])).data.skills.groups[0].gems[0].quality, before.data.skills.groups[0].gems[0].quality);
  await assert.rejects(foundation.deriveGem(parent.id, 1, 1, { qualityId: 'Divergent' }), /Invalid gem change/);
  const child = await foundation.deriveGem(parent.id, 1, 2, { level: 15, quality: 12, enabled: false });
  assert.equal(child.parentId, parent.id);
  const after = await foundation.inspect(child.id, ['skills']);
  const baseline = await foundation.evaluate(parent.id, ['TotalDPS']);
  const changed = await foundation.evaluate(child.id, ['TotalDPS']);
  assert.ok(baseline.metrics.TotalDPS.status === 'available' && changed.metrics.TotalDPS.status === 'available');
  assert.ok(baseline.stats.TotalDPS > changed.stats.TotalDPS && changed.stats.TotalDPS > 0);
  assert.equal(after.data.skills.groups[0].gems[1].level, 15);
  assert.equal(after.data.skills.groups[0].gems[1].quality, 12);
  assert.equal(after.data.skills.groups[0].gems[1].qualityId, before.data.skills.groups[0].gems[1].qualityId);
  assert.equal(after.data.skills.groups[0].gems[1].enabled, false);
  assert.deepEqual(after.data.skills.groups[1], before.data.skills.groups[1]);
  assert.deepEqual((await foundation.inspect(parent.id, ['skills'])).data.skills, before.data.skills);
  assert.equal(await foundation.exportBuild(parent.id), xml);
  await assert.rejects(foundation.deriveGem(parent.id, 1, 99, { level: 2 }), /Gem not found/);
  await assert.rejects(foundation.deriveGem(parent.id, 1, 2, { quality: 100 }), /Invalid gem change/);
  const added = await foundation.deriveGemList(parent.id, 1, { type: 'add', gemName: 'Fireball', level: 12, quality: 5, insertIndex: 2 });
  const withAdded = (await foundation.inspect(added.id, ['skills'])).data.skills;
  assert.equal(withAdded.groups[0].gems.length, 3);
  assert.equal(withAdded.groups[0].gems[1].name, 'Fireball');
  assert.equal(withAdded.groups[0].gems[1].level, 12);
  assert.equal(withAdded.groups[0].gems[1].quality, 5);
  const removed = await foundation.deriveGemList(added.id, 1, { type: 'remove', gemIndex: 2 });
  assert.deepEqual((await foundation.inspect(removed.id, ['skills'])).data.skills, before.data.skills);
  await assert.rejects(foundation.deriveGemList(parent.id, 1, { type: 'add', gemName: 'No Such Gem Fixture' }), /unrecognized gem/);
  await assert.rejects(foundation.deriveGemList(parent.id, 1, { type: 'remove', gemIndex: 99 }), /Gem not found/);
  const replaced = await foundation.deriveSupportReplacement(parent.id, 1, 2, { gemName: 'Controlled Destruction Support', level: 18, quality: 7 }, true);
  assert.equal(replaced.parentId, parent.id);
  const replacedSkills = (await foundation.inspect(replaced.id, ['skills'])).data.skills;
  assert.equal(replacedSkills.groups[0].gems[1].name, 'Controlled Destruction');
  assert.equal(replacedSkills.groups[0].gems[1].level, 18);
  assert.equal(replacedSkills.groups[0].gems[1].quality, 7);
  assert.deepEqual(replacedSkills.groups[0].gems[0], before.data.skills.groups[0].gems[0]);
  assert.deepEqual(replacedSkills.groups[1], before.data.skills.groups[1]);
  const beforeFailure = (await foundation.listSnapshots()).snapshots.length;
  await assert.rejects(foundation.deriveSupportReplacement(parent.id, 1, 2, { gemName: 'No Such Gem Fixture' }, true), /unrecognized gem/);
  assert.equal((await foundation.listSnapshots()).snapshots.length, beforeFailure);
  const setup = await foundation.deriveGemSetup(parent.id, 1, [{ gemName: 'Arc', level: 19 }, { gemName: 'Controlled Destruction Support', quality: 7 }, { gemName: 'Faster Casting Support' }], true);
  const setupSkills = (await foundation.inspect(setup.id, ['skills'])).data.skills;
  assert.deepEqual(setupSkills.groups[0].gems.map(gem => gem.name), ['Arc', 'Controlled Destruction', 'Faster Casting']);
  assert.equal(setupSkills.groups[0].gems[0].level, 19);
  assert.equal(setupSkills.groups[0].gems[1].quality, 7);
  assert.deepEqual(setupSkills.groups[1], before.data.skills.groups[1]);
  const beforeSetupFailure = (await foundation.listSnapshots()).snapshots.length;
  await assert.rejects(foundation.deriveGemSetup(parent.id, 1, [{ gemName: 'Arc' }, { gemName: 'Controlled Destruction Support' }, { gemName: 'No Such Gem Fixture' }], true), /unrecognized gem/);
  assert.equal((await foundation.listSnapshots()).snapshots.length, beforeSetupFailure);
  const combined = await foundation.deriveSkillGroup(parent.id, { label: 'atomic', slot: 'Boots', enabled: true, includeInFullDPS: true }, [
    { gemName: 'Arc', level: 18, quality: 10 }, { gemName: 'Added Lightning Damage Support', level: 15, enabled: false },
  ]);
  const combinedSkills = (await foundation.inspect(combined.id, ['skills'])).data.skills;
  assert.equal(combinedSkills.groups.length, 3);
  assert.equal(combinedSkills.groups[2].label, 'atomic');
  assert.equal(combinedSkills.groups[2].slot, 'Boots');
  assert.equal(combinedSkills.groups[2].includeInFullDPS, true);
  assert.deepEqual(combinedSkills.groups[2].gems.map(gem => gem.name), ['Arc', 'Added Lightning Damage']);
  assert.equal(combinedSkills.groups[2].gems[1].enabled, false);
  const emptyGroup = await foundation.deriveSkillGroup(parent.id, {}, []);
  const emptySkills = (await foundation.inspect(emptyGroup.id, ['skills'])).data.skills;
  assert.equal(emptySkills.groups[2].gems.length, 0);
  assert.equal(emptySkills.groups[2].includeInFullDPS, false);
  const snapshotCount = (await foundation.listSnapshots()).snapshots.length;
  await assert.rejects(foundation.deriveSkillGroup(parent.id, { slot: 'Boots' }, [{ gemName: 'Arc' }, { gemName: 'No Such Gem Fixture' }]), /unrecognized gem/);
  assert.equal((await foundation.listSnapshots()).snapshots.length, snapshotCount);
  assert.deepEqual((await foundation.inspect(parent.id, ['skills'])).data.skills, before.data.skills);
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: options.adapterPath });
  mcp.child.stderr.on('data', () => {});
  const exited = once(mcp.child, 'exit');
  try {
    await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'gem-smoke', version: '1' } });
    mcp.notify('notifications/initialized', {});
    const guarded = await mcp.request('tools/call', { name: 'foundation_derive_level', arguments: { snapshot_id: legacyParent.id, level: 70 } });
    assert.equal(guarded.result.isError, true);
    assert.match(guarded.result.content[0].text, /non-default gem qualityId/);
    const response = await mcp.request('tools/call', { name: 'foundation_derive_gem', arguments: { snapshot_id: parent.id, group_index: 1, gem_index: 2, changes: { level: 15, quality: 12, enabled: false }, trial: true } });
    assert.ok(!response.error && !response.result?.isError, JSON.stringify(response));
    const trial = JSON.parse(response.result.content[0].text);
    assert.equal(trial.parentId, parent.id);
    assert.equal(trial.retention.kind, 'trial');
    const qualityResponse = await mcp.request('tools/call', { name: 'foundation_derive_gem', arguments: { snapshot_id: parent.id, group_index: 1, gem_index: 1, changes: { qualityId: 'Default', quality: 12 }, trial: true } });
    assert.ok(!qualityResponse.error && !qualityResponse.result?.isError, JSON.stringify(qualityResponse));
    const qualityTrial = JSON.parse(qualityResponse.result.content[0].text);
    assert.equal((await foundation.inspect(qualityTrial.id, ['skills'])).data.skills.groups[0].gems[0].quality, 12);
    const replaceResponse = await mcp.request('tools/call', { name: 'foundation_replace_support', arguments: { snapshot_id: parent.id, group_index: 1, gem_index: 2, replacement: { gemName: 'Controlled Destruction Support' }, trial: true } });
    assert.ok(!replaceResponse.error && !replaceResponse.result?.isError, JSON.stringify(replaceResponse));
    const replacementTrial = JSON.parse(replaceResponse.result.content[0].text);
    assert.equal(replacementTrial.parentId, parent.id); assert.equal(replacementTrial.retention.kind, 'trial');
    const setupResponse = await mcp.request('tools/call', { name: 'foundation_derive_gem_setup', arguments: { snapshot_id: parent.id, group_index: 1, gems: [{ gemName: 'Arc' }, { gemName: 'Controlled Destruction Support' }, { gemName: 'Faster Casting Support' }], trial: true } });
    assert.ok(!setupResponse.error && !setupResponse.result?.isError, JSON.stringify(setupResponse));
    const setupTrial = JSON.parse(setupResponse.result.content[0].text);
    assert.equal(setupTrial.parentId, parent.id); assert.equal(setupTrial.retention.kind, 'trial');
    const setupComparison = await mcp.request('tools/call', { name: 'compare_snapshot_gem_setups', arguments: { snapshot_id: parent.id, group_index: 1, candidate_snapshot_ids: [setupTrial.id] } });
    assert.ok(!setupComparison.error && !setupComparison.result?.isError, JSON.stringify(setupComparison));
    assert.equal(JSON.parse(setupComparison.result.content[0].text).results[0].status, 'ok');
    const rankingResponse = await mcp.request('tools/call', { name: 'rank_snapshot_supports', arguments: { snapshot_id: parent.id, group_index: 1, gem_index: 2, metric: 'CombinedDPS', candidates: [{ gem_name: 'Controlled Destruction Support' }, { gem_name: 'No Such Gem Fixture' }] } });
    assert.ok(!rankingResponse.error && !rankingResponse.result?.isError, JSON.stringify(rankingResponse));
    const ranking = JSON.parse(rankingResponse.result.content[0].text);
    assert.deepEqual(ranking.rankedCandidates, ['Controlled Destruction Support']);
    assert.equal(ranking.results[0].gem.appliedToSelectedSkill, true);
    assert.equal(ranking.results[1].status, 'error');
    const directRanked = await foundation.evaluate(ranking.results[0].snapshotId, ['CombinedDPS']);
    assert.equal(ranking.results[0].value, directRanked.metrics.CombinedDPS.value);
    const fullBatch = await mcp.request('tools/call', { name: 'rank_snapshot_supports', arguments: { snapshot_id: parent.id, group_index: 1, gem_index: 2, metric: 'CombinedDPS', candidates: [{ gem_name: 'Controlled Destruction Support' }, { gem_name: 'Added Lightning Damage Support' }, { gem_name: 'Faster Casting Support' }, { gem_name: 'Spell Echo Support' }] } });
    assert.ok(!fullBatch.error && !fullBatch.result?.isError, JSON.stringify(fullBatch));
    assert.equal(JSON.parse(fullBatch.result.content[0].text).results.length, 4);
    const replacedComparison = await mcp.request('tools/call', { name: 'compare_snapshot_gem_setups', arguments: { snapshot_id: parent.id, group_index: 1, candidate_snapshot_ids: [replacementTrial.id] } });
    assert.ok(!replacedComparison.error && !replacedComparison.result?.isError, JSON.stringify(replacedComparison));
    assert.equal(JSON.parse(replacedComparison.result.content[0].text).results[0].status, 'ok');
    const comparison = await mcp.request('tools/call', { name: 'compare_snapshot_gem_setups', arguments: { snapshot_id: parent.id, group_index: 1, candidate_snapshot_ids: [trial.id] } });
    assert.ok(!comparison.error && !comparison.result?.isError, JSON.stringify(comparison));
    const compared = JSON.parse(comparison.result.content[0].text);
    assert.equal(compared.results[0].status, 'ok', JSON.stringify(compared.results[0]));
    const expectedParent = await foundation.evaluate(parent.id, ['CombinedDPS']);
    const expectedTrial = await foundation.evaluate(trial.id, ['CombinedDPS']);
    assert.equal(compared.results[0].metrics.CombinedDPS.delta, expectedTrial.metrics.CombinedDPS.value - expectedParent.metrics.CombinedDPS.value);
    const inspected = await mcp.request('tools/call', { name: 'foundation_inspect', arguments: { snapshot_id: trial.id, sections: ['skills'] } });
    assert.ok(!inspected.error && !inspected.result?.isError, JSON.stringify(inspected));
    assert.equal(JSON.parse(inspected.result.content[0].text).data.skills.groups[0].gems[1].quality, 12);
    const addResult = await mcp.request('tools/call', { name: 'foundation_derive_gem_list', arguments: { snapshot_id: parent.id, group_index: 1, operation: { type: 'add', gemName: 'Fireball', insertIndex: 2 }, trial: true } });
    assert.ok(!addResult.error && !addResult.result?.isError, JSON.stringify(addResult));
    assert.equal(JSON.parse(addResult.result.content[0].text).retention.kind, 'trial');
    const groupResult = await mcp.request('tools/call', { name: 'foundation_derive_skill_group', arguments: { snapshot_id: parent.id, group: { label: 'test', slot: 'Boots' }, gems: [{ gemName: 'Arc' }], trial: true } });
    assert.ok(!groupResult.error && !groupResult.result?.isError, JSON.stringify(groupResult));
    assert.equal(JSON.parse(groupResult.result.content[0].text).retention.kind, 'trial');
    mcp.child.stdin.end(); assert.equal((await exited)[0], 0);
  } finally { if (mcp.child.exitCode === null && mcp.child.signalCode === null) { mcp.child.kill('SIGTERM'); await exited; } }
  console.log('foundation gem mutation passed');
} finally { await client.stop(); await rm(dir, { recursive: true, force: true }); }
