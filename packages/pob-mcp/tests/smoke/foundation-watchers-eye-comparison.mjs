import { strict as assert } from 'node:assert';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { PoBLuaApiClient } from '../../build/adapters/pob/bridge.js';
import { PoBWatchersEyeSource } from '../../build/adapters/watchersEye/pobSource.js';
import { smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';

const dir = await mkdtemp(join(tmpdir(), 'pob-watcher-comparison-'));
const client = new PoBLuaApiClient({ cwd: smokePoBSrc(), cmd: process.env.POB_CMD, args: [resolve('lua/vanilla_stdio_bridge.lua')], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
let child;
try {
  await client.start();
  await client.loadBuildXml(await readFile(resolve('tests/fixtures/cluster-toxic-rain.xml'), 'utf8'));
  const originalXml = await client.exportBuildXml();
  const groupIndex = 4;
  await client.addGem({ groupIndex, gemName: 'Grace', level: 20 });
  const xml = await client.exportBuildXml();
  await client.loadBuildXml(originalXml);
  const extra = await client.createSocketGroup({ label: 'watcher-aura', slot: 'Helmet', enabled: true });
  await client.addGem({ groupIndex: extra.index, gemName: 'Grace', level: 20 });
  const reorderedXml = await client.exportBuildXml();
  await client.loadBuildXml(xml);
  const source = new PoBWatchersEyeSource().read();
  const modifier = source.entries.find(entry => entry.id === 'GraceChanceToDodge');
  assert.ok(modifier?.lines.includes('+(12-15)% chance to Suppress Spell Damage while affected by Grace'));
  const item = "Rarity: UNIQUE\nWatcher's Eye\nPrismatic Jewel\nImplicits: 0\n+15% chance to Suppress Spell Damage while affected by Grace";
  const fields = ['SpellSuppressionChance'];
  const before = await client.getStats(fields);
  await client.addItem(item, 'Jewel 34483');
  const after = await client.getStats(fields);
  assert.ok(Number.isFinite(before.SpellSuppressionChance) && Number.isFinite(after.SpellSuppressionChance));
  assert.ok(after.SpellSuppressionChance > before.SpellSuppressionChance);
  await client.loadBuildXml(reorderedXml);
  const reorderedBefore = await client.getStats(fields);
  await client.addItem(item, 'Jewel 34483');
  const reorderedAfter = await client.getStats(fields);
  await client.stop();

  const mcp = startMcpServer({ POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: resolve('lua/vanilla_stdio_bridge.lua') });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'watcher-comparison-smoke', version: '1' } });
  mcp.notify('notifications/initialized', {});
  const call = async (name, args) => {
    const response = await mcp.request('tools/call', { name, arguments: args });
    assert.ok(!response.error && !response.result?.isError, JSON.stringify(response).slice(0, 1600));
    return JSON.parse(response.result.content[0].text);
  };
  const parent = await call('foundation_import_build', { xml, source: 'watcher-comparison-fixture' });
  const discovery = await call('inspect_snapshot_watchers_eye', { snapshot_id: parent.id });
  assert.equal(discovery.source.sha256, source.sha256);
  const aura = discovery.candidates.find(candidate => candidate.groupIndex === groupIndex && candidate.gemName === 'Grace');
  assert.equal(aura.enabledState, 'enabled_in_pob');
  assert.deepEqual(aura.modifiers.find(candidate => candidate.id === modifier.id), modifier);
  const report = await call('compare_snapshot_jewels', { snapshot_id: parent.id, socket_node_id: 34483, fields, candidates: [{ name: 'watcher', item_text: item }] });
  const candidate = report.results[0];
  assert.equal(candidate.status, 'compared', JSON.stringify(candidate));
  const metric = candidate.comparison.metrics.SpellSuppressionChance;
  assert.ok(Math.abs(metric.baseline.value - before.SpellSuppressionChance) < 0.01);
  assert.ok(Math.abs(metric.candidate.value - after.SpellSuppressionChance) < 0.01);
  assert.ok(Math.abs(metric.delta - (after.SpellSuppressionChance - before.SpellSuppressionChance)) < 0.01, JSON.stringify({ metric, contextDifferent: candidate.comparison.contextDifferent }));
  assert.equal(candidate.snapshot.parentId, parent.id);
  assert.equal((await call('foundation_export_build', { snapshot_id: parent.id })).xml, xml);
  const reordered = await call('foundation_import_build', { xml: reorderedXml, source: 'watcher-reordered-skill-fixture' });
  const partial = await call('compare_snapshot_jewels', { snapshot_id: reordered.id, socket_node_id: 34483, fields, candidates: [{ name: 'watcher', item_text: item }] });
  const uncertain = partial.results[0].comparison;
  assert.equal(uncertain.contextDifferent, false);
  assert.equal(uncertain.contextComparison, 'generated_group_reindexed');
  assert.equal(uncertain.metrics.SpellSuppressionChance.status, 'context_reindexed_unverified');
  assert.ok(Math.abs(uncertain.metrics.SpellSuppressionChance.delta - (reorderedAfter.SpellSuppressionChance - reorderedBefore.SpellSuppressionChance)) < 0.01);
  assert.equal((await call('foundation_export_build', { snapshot_id: reordered.id })).xml, reorderedXml);
  child.stdin.end(); assert.equal((await exited)[0], 0);
  console.log('foundation watchers eye comparison passed');
} finally {
  if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM');
  await client.stop(); await rm(dir, { recursive: true, force: true });
}
