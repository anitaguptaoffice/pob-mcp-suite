import { strict as assert } from 'node:assert';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { PoBLuaApiClient } from '../../build/pobLuaBridge.js';
import { smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';

const dir = await mkdtemp(join(tmpdir(), 'pob-paths-'));
const client = new PoBLuaApiClient({ cwd: smokePoBSrc(), cmd: process.env.POB_CMD, args: [resolve('lua/vanilla_stdio_bridge.lua')], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
let child;
try {
  await client.start(); await client.newBuild({ className: 'Witch' });
  await client.setTree({ classId: 3, ascendClassId: 0, nodes: [], treeVersion: '3_29' });
  await client.setLevel(90);
  const initialTree = await client.getTree();
  assert.equal(initialTree.nodes.length, 1);
  await assert.rejects(client.deallocateTreeNode(initialTree.nodes[0]), /starting node/);
  const xml = await client.exportBuildXml();
  const native = await client.searchNodes({ keyword: "Arcanist's Dominion", nodeType: 'notable', maxResults: 30, includeAllocated: false });
  const expectedPath = native.nodes.find(node => node.id === 11420)?.pathNodes;
  assert.deepEqual(expectedPath, [57264, 37569, 36542, 4397, 11420]);
  await client.stop();
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: resolve('lua/vanilla_stdio_bridge.lua') });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'paths-smoke', version: '1' } });
  mcp.notify('notifications/initialized', {});
  const call = async (name, args) => {
    const response = await mcp.request('tools/call', { name, arguments: args });
    assert.ok(!response.error && !response.result?.isError, JSON.stringify(response));
    return JSON.parse(response.result.content[0].text);
  };
  const parent = await call('foundation_import_build', { xml, source: 'paths-fixture' });
  const path = await call('find_snapshot_tree_path', { snapshot_id: parent.id, target_node_id: 11420 });
  assert.equal(path.treeVersion, '3_29');
  assert.equal(path.node.status, 'reachable');
  assert.deepEqual(path.node.pathNodes, expectedPath);
  assert.equal(path.node.pointCost, 5);
  const nearby = await call('find_snapshot_nearby_nodes', { snapshot_id: parent.id, max_distance: 8, limit: 2, filter: 'spell damage' });
  assert.ok(nearby.total >= 1 && nearby.nodes.some(node => node.id === 11420));
  assert.ok(nearby.nodes.length <= 2 && nearby.nodes.every(node => node.pointCost <= 8));
  const empty = await call('find_snapshot_nearby_nodes', { snapshot_id: parent.id, max_distance: 1, filter: 'not a real stat' });
  assert.equal(empty.total, 0); assert.deepEqual(empty.nodes, []);
  const absent = await call('find_snapshot_tree_path', { snapshot_id: parent.id, target_node_id: 2147483647 });
  assert.equal(absent.status, 'not_found');
  const unreachable = await call('find_snapshot_tree_path', { snapshot_id: parent.id, target_node_id: 27054 });
  assert.equal(unreachable.node.status, 'unreachable'); assert.deepEqual(unreachable.node.pathNodes, []);
  const derived = await call('foundation_derive_tree', { snapshot_id: parent.id, add_nodes: path.node.pathNodes });
  const after = await call('find_snapshot_tree_path', { snapshot_id: derived.id, target_node_id: 11420 });
  assert.equal(after.node.status, 'allocated'); assert.deepEqual(after.node.pathNodes, []);
  await client.start();
  await client.loadBuildXml((await call('foundation_export_build', { snapshot_id: derived.id })).xml);
  const nativeRemoval = await client.deallocateTreeNode(37569);
  assert.ok(nativeRemoval.expectedRemoved.includes(37569));
  assert.ok(nativeRemoval.expectedRemoved.includes(11420));
  const nativeRemovedTree = await client.getTree(); await client.stop();
  const removed = await call('foundation_trial_tree_removal', { snapshot_id: derived.id, node_id: 37569 });
  assert.equal(removed.parentId, derived.id); assert.equal(removed.retention.kind, 'trial');
  assert.deepEqual(removed.removed.map(entry => entry.id), nativeRemoval.expectedRemoved);
  assert.ok(removed.removed.some(entry => entry.id === 11420 && entry.name === "Arcanist's Dominion"));
  assert.deepEqual((await call('foundation_inspect', { snapshot_id: removed.id, sections: ['tree'] })).data.tree, nativeRemovedTree);
  assert.equal((await call('find_snapshot_tree_path', { snapshot_id: derived.id, target_node_id: 11420 })).node.status, 'allocated');
  const nextCandidates = await call('find_snapshot_nearby_nodes', { snapshot_id: derived.id, max_distance: 10, limit: 30 });
  const next = nextCandidates.nodes.find(node => !node.isBlighted && node.status === 'reachable');
  assert.ok(next, 'fixture requires a second reachable target');
  const sequential = await call('foundation_derive_tree', { snapshot_id: derived.id, add_nodes: next.pathNodes });
  const bundle = await call('foundation_derive_tree_paths', { snapshot_id: parent.id, targets: [11420, next.id], trial: true });
  assert.equal(bundle.parentId, parent.id); assert.equal(bundle.retention.kind, 'trial');
  assert.deepEqual(bundle.paths.map(p => p.pathNodes), [expectedPath, next.pathNodes]);
  const sequentialTree = (await call('foundation_inspect', { snapshot_id: sequential.id, sections: ['tree'] })).data.tree;
  const bundleTree = (await call('foundation_inspect', { snapshot_id: bundle.id, sections: ['tree'] })).data.tree;
  assert.deepEqual(bundleTree, sequentialTree);
  const beforeFailure = await call('foundation_list_snapshots', {});
  const rejected = await mcp.request('tools/call', { name: 'foundation_derive_tree_paths', arguments: { snapshot_id: parent.id, targets: [11420, 2147483647] } });
  assert.ok(rejected.error || rejected.result?.isError, JSON.stringify(rejected));
  assert.deepEqual(await call('foundation_list_snapshots', {}), beforeFailure);
  assert.equal((await call('find_snapshot_tree_path', { snapshot_id: parent.id, target_node_id: 11420 })).node.status, 'reachable');
  assert.equal((await call('foundation_export_build', { snapshot_id: parent.id })).xml, xml);
  child.stdin.end(); assert.equal((await exited)[0], 0);
  console.log('foundation tree paths passed');
} finally {
  if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM');
  await client.stop(); await rm(dir, { recursive: true, force: true });
}
