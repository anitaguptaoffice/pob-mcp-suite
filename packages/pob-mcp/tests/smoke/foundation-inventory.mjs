import { strict as assert } from 'node:assert';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { BuildFoundation } from '../../build/foundation/buildFoundation.js';
import { PoBLuaApiClient } from '../../build/pobLuaBridge.js';
import { SnapshotStore } from '../../build/foundation/snapshotStore.js';
import { openPoBEngine } from '../../build/foundation/pobEngineAdapter.js';
import { normalizeObservation } from '../../build/foundation/observation.js';
import { gearedBuildXml, smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';

const dir = await mkdtemp(join(tmpdir(), 'pob-inventory-'));
const options = { cwd: smokePoBSrc(), command: process.env.POB_CMD, adapterPath: resolve('lua/vanilla_stdio_bridge.lua'), timeoutMs: 60000 };
const ring = ['Item Class: Rings', 'Rarity: Rare', 'Inventory Test', 'Gold Ring', '--------', 'Item Level: 86', '--------', '+30 to maximum Life', '--------', 'Note: ~b/o 1 chaos', ''].join('\r\n');
let child;
try {
  const foundation = new BuildFoundation(new SnapshotStore(dir), () => openPoBEngine(options));
  const fixture = await readFile(gearedBuildXml, 'utf8');
  const firstSet = fixture.match(/<ItemSet\b[^>]*\bid="1"[^>]*>[\s\S]*?<\/ItemSet>/)?.[0];
  assert.ok(firstSet);
  const secondSet = firstSet.replace('id="1"', 'id="7" title="Alternative"').replace('<Slot name="Ring 1" itemId="5"/>', '<Slot name="Ring 1" itemId="0"/>');
  assert.ok(secondSet.includes('name="Ring 1" itemId="0"'));
  const bridge = new PoBLuaApiClient({ cwd: options.cwd, cmd: options.command, args: [options.adapterPath], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
  let xml;
  try {
    await bridge.start(); await bridge.loadBuildXml(fixture.replace(firstSet, `${firstSet}\n${secondSet}`));
    await bridge.createSpec({ title: 'Alternative', copyFrom: 1, activate: false });
    xml = await bridge.exportBuildXml();
  } finally { await bridge.stop(); }
  const parent = await foundation.importBuild(xml, 'inventory-fixture');
  assert.equal((await foundation.specs(parent.id)).specs.length, 2);
  assert.equal((await foundation.itemSets(parent.id)).itemSets.length, 2);
  const before = await foundation.itemInventory(parent.id, 100);
  const equipment = await foundation.inspect(parent.id, ['items']);
  const life = await foundation.evaluate(parent.id, ['Life']);
  const equipped = await foundation.deriveItem(parent.id, 'Ring 1', ring, true);
  const equippedId = (await foundation.inspect(equipped.id, ['items'])).data.items.find(item => item.slot === 'Ring 1').id;
  assert.ok(equippedId > 0 && equippedId !== 5);
  const equippedInventory = await foundation.itemInventory(equipped.id, 100);
  assert.equal(equippedInventory.total, before.total + 1);
  assert.deepEqual(equippedInventory.items.filter(item => item.id !== equippedId), before.items);
  assert.match(equippedInventory.items.find(item => item.id === equippedId).raw, /\+30 to maximum Life/);
  const equippedAlternateSet = await foundation.deriveItemSet(equipped.id, 7, true);
  assert.equal((await foundation.inspect(equippedAlternateSet.id, ['items'])).data.items.find(item => item.slot === 'Ring 1').id, 0);
  const equippedAlternateSpec = await foundation.deriveSpec(equipped.id, 2, true);
  assert.equal((await foundation.inspect(equippedAlternateSpec.id, ['items'])).data.items.find(item => item.slot === 'Ring 1').id, equippedId);
  const equippedReload = await foundation.importBuild(await foundation.exportBuild(equipped.id), 'equipped-reload');
  assert.equal((await foundation.inspect(equippedReload.id, ['items'])).data.items.find(item => item.slot === 'Ring 1').id, equippedId);
  assert.deepEqual((await foundation.itemInventory(equippedReload.id, 100)).items, equippedInventory.items);
  const derived = await foundation.deriveInventoryItem(parent.id, ring, true);
  const after = await foundation.itemInventory(derived.id, 100);
  assert.equal(after.total, before.total + 1);
  const added = after.items.filter(item => !before.items.some(old => old.id === item.id));
  assert.equal(added.length, 1); assert.match(added[0].raw, /\+30 to maximum Life/);
  assert.deepEqual(normalizeObservation({ items: (await foundation.inspect(derived.id, ['items'])).data.items }).items, normalizeObservation({ items: equipment.data.items }).items);
  assert.equal((await foundation.evaluate(derived.id, ['Life'])).stats.Life, life.stats.Life);
  const alternateSet = await foundation.deriveItemSet(derived.id, 7, true);
  assert.equal((await foundation.inspect(alternateSet.id, ['items'])).data.items.find(item => item.slot === 'Ring 1').id, 0);
  const alternateSpec = await foundation.deriveSpec(derived.id, 2, true);
  assert.equal((await foundation.specs(alternateSpec.id)).activeSpec, 2);
  const emptyAlternate = await foundation.deriveItemSet(parent.id, 7, true);
  const auto = await foundation.deriveAutoItem(emptyAlternate.id, ring, true);
  assert.equal(auto.slot, 'Ring 1');
  const restoredSet = await foundation.deriveItemSet(auto.snapshot.id, 1, true);
  assert.equal((await foundation.inspect(restoredSet.id, ['items'])).data.items.find(item => item.slot === 'Ring 1').id, 5);
  const copiedSpec = await foundation.deriveSpec(auto.snapshot.id, 2, true);
  assert.equal((await foundation.specs(copiedSpec.id)).activeSpec, 2);
  assert.equal(await foundation.exportBuild(parent.id), xml);
  const imported = await foundation.importBuild(await foundation.exportBuild(derived.id), 'inventory-reload');
  assert.deepEqual((await foundation.itemInventory(imported.id, 100)).items, after.items);
  const first = await foundation.itemInventory(derived.id, 1);
  const second = await foundation.itemInventory(derived.id, 1, first.nextAfterItemId);
  assert.notEqual(first.items[0].id, second.items[0].id);
  const snapshots = await foundation.listSnapshots();
  await assert.rejects(foundation.deriveInventoryItem(parent.id, 'not an item'));
  assert.deepEqual(await foundation.listSnapshots(), snapshots);
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: options.adapterPath });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'inventory-smoke', version: '1' } });
  mcp.notify('notifications/initialized', {});
  const response = await mcp.request('tools/call', { name: 'foundation_item_inventory', arguments: { snapshot_id: derived.id, limit: 100 } });
  assert.ok(!response.error && !response.result?.isError, JSON.stringify(response));
  assert.deepEqual(JSON.parse(response.result.content[0].text).items, after.items);
  const add = await mcp.request('tools/call', { name: 'foundation_derive_inventory_item', arguments: { snapshot_id: parent.id, item_text: ring, trial: true } });
  assert.ok(!add.error && !add.result?.isError, JSON.stringify(add));
  assert.equal(JSON.parse(add.result.content[0].text).parentId, parent.id);
  child.stdin.end(); assert.equal((await exited)[0], 0);
  console.log('foundation unequipped item inventory passed');
} finally {
  if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM');
  await rm(dir, { recursive: true, force: true });
}
