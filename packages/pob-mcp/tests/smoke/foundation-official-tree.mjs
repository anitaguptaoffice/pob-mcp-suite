import { strict as assert } from 'node:assert';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { PoBLuaApiClient } from '../../build/adapters/pob/bridge.js';
import { gearedBuildXml, smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';

const dir = await mkdtemp(join(tmpdir(), 'pob-official-tree-'));
const client = new PoBLuaApiClient({ cwd: smokePoBSrc(), cmd: process.env.POB_CMD, args: [resolve('lua/vanilla_stdio_bridge.lua')], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
let child;
try {
  const xml = await readFile(gearedBuildXml, 'utf8');
  const url = xml.match(/https:\/\/www\.pathofexile\.com\/passive-skill-tree\/[A-Za-z0-9_=-]+/)?.[0];
  assert.ok(url);
  await client.start(); await client.loadBuildXml(xml);
  const native = await client.getTree();
  assert.equal(native.treeVersion, '3_13');
  await client.newBuild({ className: 'Witch' });
  await client.setTree({ classId: 3, ascendClassId: 0, nodes: [], treeVersion: '3_29' });
  await client.setLevel(90);
  const empty = await client.getTree(), emptyXml = await client.exportBuildXml();
  const searched = await client.searchNodes({ keyword: 'Life Mastery', nodeType: 'mastery', maxResults: 100, includeAllocated: false });
  const masteryPath = searched.nodes.find(node => node.id === 4139)?.pathNodes;
  assert.ok(masteryPath?.includes(4139));
  const words = values => values.flatMap(value => [value >> 8, value & 255]);
  const masteryCode = Buffer.from([0, 0, 0, 6, 3, 0, masteryPath.length, ...words(masteryPath), 0, 1, ...words([47642, 4139])]).toString('base64url');
  await client.setTree({ ...empty, nodes: [...empty.nodes, ...masteryPath], masteryEffects: { 4139: 47642 } });
  const masteryNative = await client.getTree(); await client.stop();
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: resolve('lua/vanilla_stdio_bridge.lua') });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'official-tree-smoke', version: '1' } }); mcp.notify('notifications/initialized', {});
  const call = async (name, args) => { const response = await mcp.request('tools/call', { name, arguments: args }); assert.ok(!response.error && !response.result?.isError, JSON.stringify(response).slice(0, 1800)); return JSON.parse(response.result.content[0].text); };
  const parent = await call('foundation_import_build', { xml, source: 'official-tree-fixture' });
  const result = await call('derive_snapshot_official_tree', { snapshot_id: parent.id, code: url, tree_version: '3_13' });
  assert.equal(result.snapshot.parentId, parent.id); assert.equal(result.snapshot.retention.kind, 'trial');
  assert.equal(result.decoded.treeVersion, null);
  const actual = await call('foundation_inspect', { snapshot_id: result.snapshot.id, sections: ['tree'] });
  assert.deepEqual(actual.data.tree, native);
  assert.equal((await call('foundation_export_build', { snapshot_id: parent.id })).xml, xml);
  const before = await call('foundation_list_snapshots', {});
  const failed = await mcp.request('tools/call', { name: 'derive_snapshot_official_tree', arguments: { snapshot_id: parent.id, code: url, tree_version: '3_29' } });
  assert.ok(failed.error || failed.result?.isError, JSON.stringify(failed));
  assert.deepEqual(await call('foundation_list_snapshots', {}), before);
  const masteryParent = await call('foundation_import_build', { xml: emptyXml, source: 'official-tree-mastery' });
  const masteryResult = await call('derive_snapshot_official_tree', { snapshot_id: masteryParent.id, code: masteryCode, tree_version: '3_29' });
  assert.equal(masteryResult.decoded.masteryEffects['4139'], 47642);
  assert.deepEqual((await call('foundation_inspect', { snapshot_id: masteryResult.snapshot.id, sections: ['tree'] })).data.tree, masteryNative);
  assert.equal((await call('foundation_export_build', { snapshot_id: masteryParent.id })).xml, emptyXml);
  child.stdin.end(); assert.equal((await exited)[0], 0);
  console.log('foundation official tree import passed');
} finally { if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM'); await client.stop(); await rm(dir, { recursive: true, force: true }); }
