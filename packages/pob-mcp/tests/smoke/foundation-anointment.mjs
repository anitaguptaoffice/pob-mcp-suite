import { strict as assert } from 'node:assert';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { PoBLuaApiClient } from '../../build/pobLuaBridge.js';
import { gearedBuildXml, smokePoBSrc } from './pobSource.mjs';
import { startMcpServer } from './mcpClient.mjs';
const dir = await mkdtemp(join(tmpdir(), 'pob-anoint-'));
const client = new PoBLuaApiClient({ cwd: smokePoBSrc(), cmd: process.env.POB_CMD, args: [resolve('lua/vanilla_stdio_bridge.lua')], env: { POB_API_STDIO: '0' }, timeoutMs: 60000 });
let child;
try {
  await client.start(); await client.loadBuildXml(await readFile(gearedBuildXml, 'utf8'));
  const group = await client.createSocketGroup({ label: 'poison-minion', slot: 'Helmet' });
  await client.addGem({ groupIndex: group.index, gemName: 'Summon Raging Spirit', level: 20 });
  await client.setMainSelection({ mainSocketGroup: group.index });
  assert.ok((await client.setConfig({ customMods: 'Minions have 100% chance to Poison on Hit' })).applied.customMods);
  await client.addItem('Rarity: RARE\nFixture Belt\nLeather Belt\nItem Level: 80\nImplicits: 1\n+25 to maximum Life\nThis item can be anointed by Cassia', 'Belt');
  const stats = await client.getStats(['MinionCombinedDPS', 'MinionTotalDPS']);
  assert.ok(stats.MinionCombinedDPS > stats.MinionTotalDPS && stats.MinionTotalDPS > 0);
  const itemsBefore = await client.getItems();
  await assert.rejects(client.evaluateAnointCandidates({ slot: 'Amulet', focus: 'dps', damageMetric: 'NotARealMetric' }), /invalid damage metric/);
  assert.deepEqual(await client.getItems(), itemsBefore);
  const native = await client.evaluateAnointCandidates({ slot: 'Amulet', focus: 'dps', damageMetric: 'MinionCombinedDPS', limit: 5 });
  assert.deepEqual(await client.getItems(), itemsBefore);
  assert.equal(native.base.damageStat, 'MinionCombinedDPS'); assert.ok(native.evaluated > 0 && native.candidates.length > 0);
  const nativeBelt = await client.evaluateAnointCandidates({ slot: 'Belt', focus: 'defence', limit: 3 });
  assert.ok(nativeBelt.evaluated > 0 && nativeBelt.base.TotalEHP > 0);
  assert.deepEqual(await client.getItems(), itemsBefore);
  const { xml } = await client.unchangedItemsSnapshot(); await client.stop();
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'false', POB_SNAPSHOT_DIRECTORY: dir, POB_ADAPTER_PATH: resolve('lua/vanilla_stdio_bridge.lua') });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'anointment-smoke', version: '1' } }); mcp.notify('notifications/initialized', {});
  const call = async (name, args) => { const response = await mcp.request('tools/call', { name, arguments: args }); assert.ok(!response.error && !response.result?.isError, JSON.stringify(response).slice(0, 1000)); return JSON.parse(response.result.content[0].text); };
  const parent = await call('foundation_import_build', { xml, source: 'poison-anoint-fixture' });
  const result = await call('rank_snapshot_anointments', { snapshot_id: parent.id, slot: 'Amulet', focus: 'dps', damage_metric: 'MinionCombinedDPS', limit: 5 });
  assert.equal(result.baseline.kind, 'item_without_selected_enchantment'); assert.equal(result.baseline.removedEnchant, native.selectedEnchant); assert.equal(result.baseline.damageMetric, 'MinionCombinedDPS');
  assert.ok(Math.abs(result.baseline.damageValue - native.base.damageValue) < 0.01);
  assert.ok(Math.abs(result.candidates[0].score - native.candidates[0].score) < 0.01);
  assert.equal(result.evaluated, native.evaluated); assert.equal(result.skipped, native.skipped);
  const belt = await call('rank_snapshot_anointments', { snapshot_id: parent.id, slot: 'Belt', focus: 'defence', limit: 3 });
  assert.equal(belt.baseline.damageMetric, null); assert.equal(belt.baseline.totalEhp, nativeBelt.base.TotalEHP);
  assert.equal(belt.candidates[0].score, nativeBelt.candidates[0].score);
  assert.equal((await call('foundation_export_build', { snapshot_id: parent.id })).xml, xml);
  child.stdin.end(); assert.equal((await exited)[0], 0); console.log('foundation anointment passed');
} finally { if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM'); await client.stop(); await rm(dir, { recursive: true, force: true }); }
