import { strict as assert } from 'node:assert';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { OfficialTradeAdapter } from '../../build/adapters/officialTrade/officialTradeAdapter.js';
import { TradeApiClient } from '../../build/services/tradeClient.js';
import { startMcpServer } from './mcpClient.mjs';

let calls = 0;
const source = new OfficialTradeAdapter({ fetcher: async (...args) => { calls++; return fetch(...args); }, minTimeMs: 300 });
const legacy = new TradeApiClient({ source });
const league = process.env.POE_TEST_LEAGUE || 'Standard';
const query = { query: { status: { option: 'securable' }, filters: { trade_filters: { filters: { sale_type: { option: 'priced' } } } } }, sort: { price: 'asc' } };
const first = await legacy.searchItems(league, query);
const observed = await source.search(league, query);
assert.deepEqual(observed.request, { league, query });
assert.deepEqual(first, observed.data);
assert.equal(calls, 1);
assert.ok(first.id && first.result.length > 0);
const ids = first.result.slice(0, 2);
const fromSource = await source.fetchListings(ids, first.id);
const fromLegacy = await legacy.fetchItems(ids, first.id);
assert.equal(calls, 2);
assert.deepEqual(fromLegacy.map(item => item.id), fromSource.data.listings.map(item => item.id));
assert.ok(fromSource.fetchedAt && fromSource.source === 'official-trade');
const dir = await mkdtemp(join(tmpdir(), 'pob-shared-trade-'));
let child;
try {
  const mcp = startMcpServer({ POB_FOUNDATION_ENABLED: 'true', POB_LEGACY_ENABLED: 'true', POB_LUA_ENABLED: 'false', POE_TRADE_ENABLED: 'true', POE_SESSION_ID: '', POB_DIRECTORY: dir, POB_SNAPSHOT_DIRECTORY: join(dir, 'snapshots'), POB_ADAPTER_PATH: resolve('lua/vanilla_stdio_bridge.lua') });
  child = mcp.child; child.stderr.on('data', () => {}); const exited = once(child, 'exit');
  await mcp.request('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'shared-trade-live', version: '1' } }); mcp.notify('notifications/initialized', {});
  const call = async name => { const response = await mcp.request('tools/call', { name, arguments: { league, item_type: 'Gold Ring', limit: 1, audit_sources: false } }); assert.ok(!response.error && !response.result?.isError, JSON.stringify(response).slice(0, 1000)); return response.result.content[0].text; };
  const legacyResponse = await call('search_trade_items');
  assert.match(legacyResponse, /securable/);
  const modern = JSON.parse(await call('search_official_trade'));
  assert.equal(modern.query.query.status.option, 'securable');
  assert.equal(modern.query.query.filters.trade_filters.filters.sale_type.option, 'priced');
  assert.equal(modern.listingScope, 'instant_buyout');
  child.stdin.end(); assert.equal((await exited)[0], 0);
} finally { if (child && child.exitCode === null && child.signalCode === null) child.kill('SIGTERM'); await rm(dir, { recursive: true, force: true }); }
console.log('shared Trade live source passed');
